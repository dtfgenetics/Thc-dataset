import { describe, expect, it } from 'vitest'
import { categoryOrder, issues } from '../data/catalog'

const bySlug = (slug: string) => {
  const record = issues.find((item) => item.slug === slug)
  if (!record) throw new Error(`Missing diagnostic profile: ${slug}`)
  return record
}

describe('canonical diagnostic catalog accuracy expansion', () => {
  it('keeps Alternaria assay context and Botrytis look-alikes separate from field ground truth', () => {
    const record = bySlug('alternaria-leaf-spot')
    const study = record.sources.find((item) => item.doi === '10.3390/plants9070882')!
    expect(study.authors).toEqual(['Shachar Jerushalmi', 'Marcel Maymon', 'Aviv Dombrovsky', 'Stanley Freeman'])
    expect(study.publicationDate).toBe('2020-07-13')
    expect(study.accessedDate).toBe('2026-10-15')
    expect(study.supportedClaims.join(' ')).toContain('isolate 22A')
    expect(study.supportedClaims.join(' ')).toContain('isolate 63A')
    expect(study.supportedClaims.join(' ')).toContain('sterile-water control')
    expect(record.indicators.join(' ')).toContain('also occurred with Botrytis')
    expect(record.lookAlikes).toContain('Botrytis foliar lesions under inoculation-assay conditions')
    expect(record.confirmation.join(' ')).toContain('detached-leaf plug assays separately from intact-plant spray assays')
    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.25)
    expect(record.warnings.join(' ')).toContain('human review')
    expect(record.media).toHaveLength(2)
    for (const media of record.media) {
      expect(media.caption).toContain('A = Alternaria alternata 22A')
      expect(media.caption).toContain('B = Botrytis cinerea 63A')
      expect(media.caption).toContain('C = sterile')
      expect(media.license).toBe('CC BY 4.0')
      expect(media.trainingEligible).toBe(false)
    }
  })
  it('keeps hemp rust paired-surface context distinct from species confirmation', () => {
    const record = bySlug('hemp-rust')
    const evidence = [...record.indicators, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    expect(record.reviewStatus).toBe('reviewed')
    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.25)
    expect(record.sources).toHaveLength(4)
    expect(record.sources.some((source) => source.url === 'https://www.npdn.org/newsletter/2025/06/identifying_microfungi_under_microscope_sample_name')).toBe(true)
    expect(record.sources[0].doi).toBe('10.32473/edis-pp379-2024')
    expect(record.sources.some((source) => source.url === 'https://solutions.tennessee.edu/?view_pub_pdf=2571')).toBe(true)
    expect(record.indicators).toHaveLength(9)
    expect(record.exclusions).toHaveLength(8)
    expect(record.lookAlikes.length).toBeGreaterThanOrEqual(14)
    expect(evidence).toContain('erumpent')
    expect(evidence).toContain('species label')
    expect(evidence).toContain('alternate host is unknown')
    const tennessee = record.sources.find((source) => source.url === 'https://solutions.tennessee.edu/?view_pub_pdf=2571')!
    expect(tennessee.accessedDate).toBe('2026-10-19')
    expect(tennessee.supportedClaims).toHaveLength(5)
    expect(tennessee.supportedClaims.join(' ')).toContain('leaf-spot ratings are not rust-resistance ratings')
    expect(tennessee.supportedClaims.join(' ')).toContain('August 26, 2019')
    expect(tennessee.supportedClaims.join(' ')).toContain('historical regional reporting, not a global first report or current prevalence estimate')
    expect(tennessee.supportedClaims.join(' ')).toContain('assignments may change with research')
    expect(evidence).toContain('do not assign infection date or transmission route')
    expect(record.media).toHaveLength(1)
    expect(record.media[0].license).toBe('CC BY-NC-ND 4.0')
    expect(record.media[0].trainingPermission).toBe('not-permitted')
    expect(record.media[0].trainingEligible).toBe(false)
  })

  it('keeps Curvularia image context distinct from species confirmation', () => {
    const record = bySlug('curvularia-leaf-spot')
    const evidence = record.confirmation.join(' ').toLowerCase()
    expect(record.reviewStatus).toBe('reviewed')
    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.2)
    expect(record.sources).toHaveLength(2)
    expect(record.sources.some((source) => source.doi === '10.1094/PDIS-03-20-0546-PDN')).toBe(true)
    expect(record.indicators).toHaveLength(8)
    expect(record.exclusions).toHaveLength(10)
    const primary = record.sources.find((source) => source.doi === '10.1094/PDIS-03-20-0546-PDN')!
    expect(primary.publicationDate).toBe('2020-10-07')
    expect(primary.accessedDate).toBe('2026-10-19')
    expect(primary.supportedClaims.join(' ')).toContain('not classifier accuracy')
    expect(primary.supportedClaims.join(' ')).toContain('25 conidia')
    expect(primary.supportedClaims.join(' ')).toContain('MT085366–MT085369')
    expect(primary.supportedClaims.join(' ')).toContain('72 hours')
    expect(evidence).toContain('calibrated microscopy')
    expect(evidence).toContain('do not manufacture individual mappings')
    expect(record.warnings.join(' ')).toContain('not an untreated field time series')
    expect(record?.lookAlikes.length).toBeGreaterThanOrEqual(14)
    expect(evidence).toContain('its, gapdh, and ef1-alpha')
    expect(evidence).toContain('cryptic-species')
    expect(record.media).toHaveLength(1)
    expect(record.media[0].license).toBe('CC BY-NC-ND 4.0')
    expect(record.media[0].trainingPermission).toBe('not-permitted')
    expect(record.media[0].trainingEligible).toBe(false)
  })

  it('keeps the UF/IFAS Xanthomonas composite reference-only and species-bounded', () => {
    const record = bySlug('xanthomonas-bacterial-leaf-spot')
    const evidence = [...record.indicators, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    const source = record.sources.find((item) => item.doi === '10.32473/edis-pp379-2024')
    const media = record.media.find((item) => item.id === 'uf-ifas-xanthomonas-field-guide-figure-15-2024')

    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.2)
    expect(source?.accessedDate).toBe('2026-10-14')
    expect(source?.supportedClaims?.join(' ')).toMatch(/diagnostic-center.*confirmation/i)
    expect(media?.license).toBe('CC BY-NC-ND 4.0')
    expect(media?.displayPermission).toBe('permitted')
    expect(media?.trainingPermission).toBe('not-permitted')
    expect(media?.trainingEligible).toBe(false)
    expect(media?.sha256).toBe('12b06502867f107461ce6ded48eef4ad56ee995f78a342bac179be6a568e6b8a')
    expect(media?.useLimitations.join(' ').toLowerCase()).toContain('no image file is stored')
    expect(evidence).toContain('current species-level linkage')
    expect(evidence).toContain('cannot confirm xanthomonas cannabis')
  })

  it('contains the expanded evidence-backed diagnostic baseline without duplicate ids or slugs', () => {
    expect(issues.length).toBeGreaterThanOrEqual(54)
    expect(new Set(issues.map((item) => item.id)).size).toBe(issues.length)
    expect(new Set(issues.map((item) => item.slug)).size).toBe(issues.length)
  })

  it('normalizes the rice root aphid DOI in the same catalog consumed by the app and exporter', () => {
    const source = bySlug('rice-root-aphid').sources.find((item) => item.title.includes('Rice Root Aphid'))
    expect(source?.doi).toBe('10.1093/jipm/pmaa008')
    expect(source?.url).toBe('https://doi.org/10.1093/jipm/pmaa008')
    expect(source?.publicationDate).toBe('2020-07-20')
  })

  it('normalizes the verified Septoria cannabicola DOI', () => {
    const source = bySlug('septoria-leaf-spot').sources.find((item) => item.title.startsWith('Septoria cannabicola'))
    expect(source?.doi).toBe('10.47371/mycosci.2023.1.004')
    expect(source?.url).toBe('https://doi.org/10.47371/mycosci.2023.1.004')
    expect(source?.publicationDate).toBe('2024-03-02')
  })

  it('keeps Septoria labels plant-linked, species-aware, and visually conservative', () => {
    const record = bySlug('septoria-leaf-spot')
    const evidence = [...record.indicators, ...record.exclusions, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    const kentucky = record.sources.find((item) => item.doi === '10.1094/PDIS-12-20-2620-SC')
    const japan = record.sources.find((item) => item.doi === '10.47371/mycosci.2023.1.004')

    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.25)
    expect(record.indicators.length).toBeGreaterThanOrEqual(8)
    expect(record.exclusions.length).toBeGreaterThanOrEqual(10)
    expect(record.progression.length).toBeGreaterThanOrEqual(5)
    expect(record.lookAlikes.length).toBeGreaterThanOrEqual(14)
    expect(record.confirmation.length).toBeGreaterThanOrEqual(8)
    expect(record.sources).toHaveLength(6)
    expect(kentucky?.authors).toHaveLength(6)
    expect(japan?.authors).toHaveLength(5)
    expect(evidence).toContain('different phylogenetic clades')
    expect(evidence).toContain('generic pcr')
    expect(evidence).toContain('human review')
    expect(record.sources.some((item) => item.doi === '10.1094/PHP-04-25-0127-RS')).toBe(true)
    expect(record.sources.some((item) => item.organization.includes('Cornell University'))).toBe(true)
    expect(record.sources.some((item) => item.doi === '10.32473/edis-pp379-2024')).toBe(true)
    expect(record.media).toHaveLength(1)
    expect(record.media[0].license).toBe('CC BY-NC-ND 4.0')
    expect(record.media[0].trainingPermission).toBe('not-permitted')
    expect(record.media[0].trainingEligible).toBe(false)
  })

  it('classifies Cannabis downy mildew as an oomycete rather than a true fungus', () => {
    expect(categoryOrder).toContain('Oomycete pathogen')
    expect(bySlug('downy-mildew-pseudoperonospora').category).toBe('Oomycete pathogen')
  })

  it('contains a distinct nematode category for root-knot nematodes', () => {
    expect(categoryOrder).toContain('Nematode')
    expect(bySlug('root-knot-nematodes').category).toBe('Nematode')
  })

  it('prevents an image-only molybdenum deficiency phenotype from becoming a confident diagnosis', () => {
    const mo = bySlug('molybdenum-low-analytical-no-visual-phenotype')
    const evidenceText = [
      mo.summary,
      ...mo.progression.map((item) => item.description),
      ...mo.confirmation,
      ...mo.warnings,
    ].join(' ').toLowerCase()
    expect(mo.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.05)
    expect(evidenceText).toContain('no visual symptoms')
    expect(evidenceText).toContain('conflict')
    expect(mo.confirmation.join(' ').toLowerCase()).toContain('photograph cannot confirm')
    expect(mo.indicators.length).toBeGreaterThanOrEqual(8)
    expect(mo.exclusions.length).toBeGreaterThanOrEqual(8)
    expect(mo.progression.length).toBeGreaterThanOrEqual(4)
    expect(mo.lookAlikes.length).toBeGreaterThanOrEqual(12)
    expect(mo.confirmation.length).toBeGreaterThanOrEqual(7)
    expect(mo.sources).toHaveLength(4)
    expect(mo.sources.some((source) => source.url.endsWith('/301400.pdf'))).toBe(true)
    expect(mo.progression.map((item) => item.description).join(' ').toLowerCase()).toMatch(/older leaves.*younger expanding leaves/)
    expect(mo.sources.some((source) => source.url === 'https://pubs.nmsu.edu/_a/A123/')).toBe(true)
    expect(mo.sources.some((source) => source.url === 'https://ask.ifas.ufl.edu/publication/EP081')).toBe(true)
    expect(mo.warnings.join(' ').toLowerCase()).toContain('human review')
    expect(mo.media).toHaveLength(0)
    const endpoint = mo.progression.find((item) => item.stage === 'Negative visual endpoint')!.description
    expect(endpoint).toContain('In the T1 experiment')
    expect(endpoint).toContain('does not negate')
    expect(endpoint).not.toContain('no supported Cannabis color')
    const clock = mo.progression.find((item) => item.stage === 'Treatment clock and capture context')!.description
    expect(clock).toContain('propagation age separate')
    const t1 = mo.sources.find((source) => source.doi === '10.3390/app9204432')!
    expect(t1.accessedDate).toBe('2026-10-15')
    expect(t1.supportedClaims.join(' ')).toContain('not plant age from seed')
  })

  it('keeps Fusarium flower/head disease separate from the root/crown profile', () => {
    const flower = bySlug('fusarium-foliar-flower-head-blight')
    const root = bySlug('fusarium-crown-root-rot')
    expect(flower.id).not.toBe(root.id)
    expect(flower.affectedParts).toContain('flowers')
    expect(root.affectedParts.some((part) => part.toLowerCase().includes('root'))).toBe(true)
  })

  it('keeps Fusarium flower/head labels plant-linked, multi-species, and visually conservative', () => {
    const record = bySlug('fusarium-foliar-flower-head-blight')
    const evidence = [...record.indicators, ...record.exclusions, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    const naturalInflorescenceStudy = record.sources.find((item) => item.doi === '10.3390/jof11070528')
    const kentuckyFlowerReport = record.sources.find((item) => item.doi === '10.1094/PDIS-06-21-1292-PDN')
    const media = record.media.find((item) => item.id === 'media-fusarium-flower-bud-figure-1')

    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.25)
    expect(record.indicators.length).toBeGreaterThanOrEqual(8)
    expect(record.exclusions.length).toBeGreaterThanOrEqual(10)
    expect(record.progression.length).toBeGreaterThanOrEqual(5)
    expect(record.lookAlikes.length).toBeGreaterThanOrEqual(14)
    expect(record.confirmation.length).toBeGreaterThanOrEqual(7)
    expect(record.sources).toHaveLength(5)
    expect(evidence).toContain('latent detection')
    expect(evidence).toContain('detached-flower')
    expect(evidence).toContain('mycotoxin')
    expect(evidence).toContain('human review')
    expect(naturalInflorescenceStudy?.authors).toEqual(['Zamir K. Punja', 'Sheryl A. Tittlemier', 'Sean Walkowiak'])
    expect(kentuckyFlowerReport?.authors).toHaveLength(6)
    expect(media?.displayPermission).toBe('permitted')
    expect(media?.trainingEligible).toBe(false)
    expect(media?.hostContext).toBe('cannabis')
  })

  it('keeps Exserohilum image-only labels conservative and linked to organism confirmation', () => {
    const record = bySlug('exserohilum-helminthosporium-leaf-blight')
    const evidence = [...record.indicators, ...record.exclusions, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    const primary = record.sources.find((item) => item.doi === '10.1094/PDIS-08-18-1434-PDN')
    const media = record.media.find((item) => item.id === 'media-exserohilum-industrial-hemp-ncsu-license-review')

    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.3)
    expect(record.progression.length).toBeGreaterThanOrEqual(5)
    expect(evidence).toContain('its1')
    expect(evidence).toContain('rpb2')
    expect(evidence).toContain('human review')
    expect(primary?.authors).toEqual(['Lindsey D. Thiessen', 'Tyler Schappe'])
    expect(primary?.publicationDate).toBe('2019-04-03')
    expect(primary?.accessedDate).toBe('2026-10-17')
    expect(primary?.supportedClaims).toHaveLength(7)
    expect(primary?.supportedClaims.join(' ')).toContain('six two-week-old Carmagnola seedlings')
    expect(primary?.supportedClaims.join(' ')).toContain('ITS1/5.8S/ITS2 region and RPB2')
    expect(primary?.supportedClaims.join(' ')).toContain('MH779469')
    expect(record.confirmation.join(' ')).toContain('culture age separately from leaf observations')
    expect(record.warnings.join(' ')).toContain('different experimental clocks')
    expect(media?.trainingEligible).toBe(false)
    expect(media?.trainingPermission).toBe('not-permitted')
    expect(media?.displayPermission).toBe('unknown')
    expect(media?.sourceUrl).toBe('https://plantpathology.ces.ncsu.edu/news/exserohilum-leaf-spot-causing-problems-in-nc-hemp/')
  })

  it('requires plant-linked evidence for Rhizoctonia and keeps symptom-only media out of training', () => {
    const record = bySlug('rhizoctonia-sore-shin-root-rot')
    const evidence = [...record.indicators, ...record.exclusions, ...record.confirmation, ...record.warnings].join(' ').toLowerCase()
    const compendium = record.sources.find((item) => item.doi === '10.1094/9780890546284.02.15.1')
    const handbook = record.sources.find((item) => item.url.includes('rhizoctonia-soreshin-root-rot'))
    const gallery = record.sources.find((item) => item.url.includes('s1084hemp/resources/images/diseases/rhizoctonia'))
    const media = record.media.find((item) => item.id === 'cornell-s1084-rhizoctonia-kentucky-field-ngauthier-2024')

    expect(record.photoOnlyMaxConfidence).toBeLessThanOrEqual(0.2)
    expect(record.progression.length).toBeGreaterThanOrEqual(5)
    expect(record.exclusions.length).toBeGreaterThanOrEqual(8)
    expect(record.lookAlikes.length).toBeGreaterThanOrEqual(12)
    expect(record.confirmation.length).toBeGreaterThanOrEqual(7)
    expect(evidence).toContain('right-angle')
    expect(evidence).toContain('human review')
    expect(compendium?.year).toBe(2022)
    expect(handbook?.year).toBe(2026)
    expect(gallery?.authors).toEqual(['Nicole Gauthier'])
    expect(gallery?.year).toBeUndefined()
    expect(gallery?.publicationDate).toBeUndefined()
    expect(gallery?.supportedClaims.join(' ')).toContain('hosting metadata')
    expect(record.sources).toHaveLength(5)
    expect(record.media).toHaveLength(1)
    expect(media?.displayPermission).toBe('unknown')
    expect(media?.trainingPermission).toBe('not-permitted')
    expect(media?.trainingEligible).toBe(false)
    expect(media?.view).toBe('whole-plant')
    expect(media?.confirmation).toBe('illustrative')
    expect(media?.sha256).toBe('8f30b81f39f690514eacb9fac97d84d810e8d22099e3af9526274bdcc8b7c3d3')
    expect(media?.perceptualHash).toBe('dhash64:6676356565e4ec4b')
  })
})
